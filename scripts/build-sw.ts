/**
 * Generates the service worker after `next build`, from the files actually in
 * the export.
 *
 * The site's whole premise involves opening it at 3,976 m with no signal, so
 * "works offline" has to be true rather than aspirational. A hand-maintained
 * precache list would rot silently; this one is derived from the build output,
 * and its version is a hash of that output, so a changed build always installs
 * a fresh cache.
 *
 *   runs automatically as npm postbuild
 */

import { createHash } from 'node:crypto';
import { readFile, readdir, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';

import { normaliseBasePath } from '../src/lib/base-path';

const OUT = path.join(process.cwd(), 'out');

/** Same variable next.config.ts reads, so the worker matches the build it ships with. */
const BASE = normaliseBasePath(process.env.PAGES_BASE_PATH);

/** Files worth holding for offline use. Source maps and the like are not. */
const PRECACHE = /\.(?:html|css|js|json|png|jpe?g|svg|webp|woff2?|ico|webmanifest)$/i;
const SKIP = /\.map$/i;

async function walk(dir: string, base = ''): Promise<string[]> {
  const out: string[] = [];
  for (const entry of await readdir(dir)) {
    const full = path.join(dir, entry);
    const rel = base ? `${base}/${entry}` : entry;
    if ((await stat(full)).isDirectory()) out.push(...(await walk(full, rel)));
    else if (PRECACHE.test(entry) && !SKIP.test(entry)) out.push(`/${rel}`);
  }
  return out;
}

async function main(): Promise<void> {
  const files = (await walk(OUT)).sort();

  // Version from content, so an unchanged build does not churn the cache.
  const hash = createHash('sha256');
  for (const f of files) hash.update(f).update(await readFile(path.join(OUT, f.slice(1))));
  const version = hash.digest('hex').slice(0, 12);

  // URLs as the browser asks for them: under the base path, plus the bare
  // directory URL a visitor actually types, which is not the same cache key as
  // index.html.
  const precache = [`${BASE}/`, ...files.map((f) => `${BASE}${f}`)];

  const sw = `/* Generated by scripts/build-sw.ts — do not edit. */
const VERSION = ${JSON.stringify(version)};
const CACHE = 'fuego-' + VERSION;
const PRECACHE = ${JSON.stringify(precache)};
const SHELL = ${JSON.stringify(`${BASE}/index.html`)};

self.addEventListener('install', (event) => {
  // Take the whole site down in one go, so a first visit on wifi is enough.
  event.waitUntil(
    caches.open(CACHE)
      .then((c) => c.addAll(PRECACHE))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  // Cache-first: on the mountain there is no network to race, and the content
  // only changes once a day.
  event.respondWith(
    caches.match(req).then((hit) => {
      if (hit) return hit;
      return fetch(req)
        .then((res) => {
          if (res.ok && res.type === 'basic') {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(req, copy));
          }
          return res;
        })
        .catch(async () => {
          // Offline and unseen: fall back to the shell so navigation still works.
          if (req.mode === 'navigate') {
            const shell = await caches.match(SHELL);
            if (shell) return shell;
          }
          return new Response('Offline', { status: 503, statusText: 'Offline' });
        });
    }),
  );
});
`;

  await writeFile(path.join(OUT, 'sw.js'), sw, 'utf8');
  const bytes = (await Promise.all(files.map(async (f) => (await stat(path.join(OUT, f.slice(1)))).size)))
    .reduce((a, b) => a + b, 0);
  console.log(`[sw] ${precache.length} URLs precached under '${BASE || '/'}', ${(bytes / 1048576).toFixed(1)} MB, version ${version}`);
}

main().catch((err) => { console.error('[sw] failed:', err); process.exitCode = 1; });
